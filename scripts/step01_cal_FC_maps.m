% Step 01: calculate the whole-surface FC maps from each individual lesion
% masks and then smooth them.
% based on the DIRECT-II dataset
% Must run along with dpabi
%
% Originally written by Xiao Chen 250929
% Stable version by Xiao Chen 261118
% chenxiaophd@gmail.com

%% initialization
clear;clc;

work_dir = 'xxxxxxx'; % the working directory
output_dir = [work_dir, '/xxxxx']; % where to output the results
mask_dir = [work_dir, '/xxxxxx']; % where to store the lesion masks

% the full subject list
SubjectListFile = 'xxxxxx/sub_list.txt'; % a txt file listing all subjects' ID

% Build a Cfg file This is config file generated by a DPABISurf pipeline.
% Here I load a existing Cfg file and change the working directory to the
% path where the preprocessed DIRECT II data stored.
load('xxxxx/Cfg_3_Processing.mat');
Cfg.WorkingDir = 'xxxxx';
Cfg.MaskFileVolu = '~/data/AllResampled_BrainMask_05_91x109x91.nii';
Cfg.SubjectID = importdata(SubjectListFile);

GSRSet = {'FunSurfWCF','FunSurfWglobalCF'};
GSRVoluSet = {'FunVoluWCF','FunVoluWglobalCF'};

% set the dpabi path
[DPABIPath, fileN, extn] = fileparts(which('DPABI.m'));
ProgramPath=fullfile(DPABIPath, 'DPARSF');
Cfg.MaskFileSurfLH = [DPABIPath, '/DPABISurf/SurfTemplates/fsaverage5_lh_cortex.label.gii'];
Cfg.MaskFileSurfRH = [DPABIPath, '/DPABISurf/SurfTemplates/fsaverage5_rh_cortex.label.gii'];

% read in the lesion subject list
demog_info = readtable([work_dir, '/xxxx.xlsx'], 'sheet', 1); % an excel file storing all the lesion subjects
subj_tumor_list = demog_info{:,1};
subj_tumor_list(1,:) =[]; %remove the example row
subj_tumor_list = cellfun(@lower, subj_tumor_list, 'UniformOutput', false); %lower_case

%% reslice the volume masks
% listing all the lesion mask files
% these files are .nii files of binary masks in the MNI space
% "wsubxxx_mask.nii.gz"
MaskVolumeSet = cell(length(subj_tumor_list),1);
for i_subj = 1:length(subj_tumor_list)
    MaskVolumeSet{i_subj} = ['w', subj_tumor_list{i_subj,1}, '_mask'];
end

for iMask = 1:length(MaskVolumeSet)
    InputFile = [mask_dir,filesep,MaskVolumeSet{iMask},'.nii.gz'];
    OutputFile = [mask_dir,filesep,MaskVolumeSet{iMask},'_Reslice.nii'];
    NewVoxSize = [];
    hld = 0;
    TargetSpace = '~/data/AllResampled_BrainMask_05_91x109x91.nii';
    y_Reslice(InputFile,OutputFile,NewVoxSize,hld, TargetSpace);
end

%% open par pool
poolobj = gcp('nocreate');
delete(poolobj);
parpool(15);

%% do calculation
for iGSR = 1:2
    Cfg.StartingDirName = GSRSet{iGSR};
    Cfg.StartingDirName_Volume = GSRVoluSet{iGSR};

    parfor i=1:length(Cfg.SubjectID)
        for iMask = 1:length(MaskVolumeSet)
                if ~exist([output_dir, filesep, 'FunVolu', filesep, ...
                        'ROISignals_',Cfg.StartingDirName_Volume, ...
                        '_', MaskVolumeSet{iMask}], 'dir')
                    mkdir([output_dir,filesep,'FunVolu',filesep, ...
                    'ROISignals_',Cfg.StartingDirName_Volume,'_', ...
                        MaskVolumeSet{iMask}]);
                end
                DirName=dir(fullfile(Cfg.WorkingDir,Cfg.StartingDirName_Volume, ...
                    Cfg.SubjectID{i},'Filtered_4DVolume.nii'));

                % extract time series
                for iFile=1:length(DirName)
                    FileName=DirName(iFile).name;
                    [ROISignalsVolume] = y_ExtractROISignal(fullfile(Cfg.WorkingDir, ...
                                Cfg.StartingDirName_Volume,Cfg.SubjectID{i},FileName), ...
                                {[mask_dir,filesep,MaskVolumeSet{iMask},'_Reslice.nii']}, ...
                                [output_dir, filesep, 'FunVolu', filesep, ...
                                'ROISignals_',Cfg.StartingDirName_Volume,'_', ...
                                MaskVolumeSet{iMask},filesep,Cfg.SubjectID{i}], ...
                                '', ... % Will not restrict into the brain mask in extracting ROI signals
                                0);
                end

                % Calculate Functional Connectivity by Seed based Correlation Anlyasis
                % Left Hemi
                if ~exist([output_dir, filesep, 'FunSurfLH', filesep, ...
                        'FC_SeedSurfLHSurfRHVolu_',Cfg.StartingDirName,'_', ...
                        MaskVolumeSet{iMask}], 'dir')

                    mkdir([output_dir,filesep,'FunSurfLH',filesep, ...
                        'FC_SeedSurfLHSurfRHVolu_',Cfg.StartingDirName,'_',MaskVolumeSet{iMask}]);
                end

                DirName=dir(fullfile(Cfg.WorkingDir,Cfg.StartingDirName,Cfg.SubjectID{i}, ...
                    '*fsaverage5_hemi-L*.func.gii'));
                for iFile=1:length(DirName)
                    FileName=DirName(iFile).name;
                    y_SCA_Surf(fullfile(Cfg.WorkingDir,Cfg.StartingDirName,Cfg.SubjectID{i},FileName), ...
                        {ROISignalsVolume}, ... 
                        [output_dir, filesep,'FunSurfLH',filesep, ...
                        'FC_SeedSurfLHSurfRHVolu_',Cfg.StartingDirName,'_',MaskVolumeSet{iMask}, ...
                        filesep,'FC_',Cfg.SubjectID{i},'.func.gii'], ...
                        Cfg.MaskFileSurfLH, ...
                        0);
                end

                % Right Hemi
                if ~exist([output_dir, filesep, 'FunSurfRH', filesep, ...
                        'FC_SeedSurfLHSurfRHVolu_', Cfg.StartingDirName, '_', MaskVolumeSet{iMask}], 'dir')
                    mkdir([output_dir,filesep,'FunSurfRH',filesep, ...
                        'FC_SeedSurfLHSurfRHVolu_',Cfg.StartingDirName, '_', MaskVolumeSet{iMask}]);
                end

                DirName=dir(fullfile(Cfg.WorkingDir,Cfg.StartingDirName,Cfg.SubjectID{i}, ...
                    '*fsaverage5_hemi-R*.func.gii'));
                for iFile=1:length(DirName)
                    FileName=DirName(iFile).name;
                    y_SCA_Surf(fullfile(Cfg.WorkingDir,Cfg.StartingDirName,Cfg.SubjectID{i},FileName), ...
                        {ROISignalsVolume}, ... 
                        [output_dir,filesep,'FunSurfRH',filesep, ...
                        'FC_SeedSurfLHSurfRHVolu_',Cfg.StartingDirName,'_',MaskVolumeSet{iMask}, ...
                        filesep,'FC_',Cfg.SubjectID{i},'.func.gii'], ...
                        Cfg.MaskFileSurfRH, ...
                        0);
                end

                % Volume
                 if (Cfg.IsProcessVolumeSpace==1) && ....
                   (~exist([output_dir,filesep,'FunVolu',filesep, ...
                   'FC_SeedSurfLHSurfRHVolu_',Cfg.StartingDirName_Volume,'_', ...
                    MaskVolumeSet{iMask}], 'dir'))

                    mkdir([output_dir,filesep,'FunVolu',filesep, ...
                            'FC_SeedSurfLHSurfRHVolu_',Cfg.StartingDirName_Volume,'_', ...
                            MaskVolumeSet{iMask}]);
                 end

                % Volume
                if (Cfg.IsProcessVolumeSpace==1)
                    % Calculate Functional Connectivity by Seed based Correlation Anlyasis
                    y_SCA([Cfg.WorkingDir,filesep,Cfg.StartingDirName_Volume,filesep,Cfg.SubjectID{i}], ...
                        {ROISignalsVolume}, ...% use extracted time series as roi
                        [output_dir,filesep,'FunVolu',filesep, ...
                        'FC_SeedSurfLHSurfRHVolu_',Cfg.StartingDirName_Volume,'_', ...
                        MaskVolumeSet{iMask},filesep,'FC_',Cfg.SubjectID{i},'.nii'], ...
                        Cfg.MaskFileVolu, ...
                        0);
                end
        end
    end
end

%% run smooth
n_par = 15; % the parallel number

% make a smoothed results folder
if ~exist([work_dir, '/raw_FC_mapsS/'], 'dir')
    mkdir([work_dir, '/raw_FC_mapsS/']);
end

% initialization
Cfg.WorkingDir = work_dir;
Cfg.SubjectNum=length(Cfg.SubjectID);
Cfg.ParallelWorkersNumber = n_par;
Cfg.Smooth.FWHMSurf = 6;
Cfg.Smooth.FWHMVolu = [6,6,6];

% prepare for the command text
CommandInit=sprintf('docker run -ti --rm -v %s:/opt/freesurfer/license.txt -v %s:/data ', ...
    fullfile(DPABIPath, 'DPABISurf', 'FreeSurferLicense', 'license.txt'), ...
    Cfg.WorkingDir);
CommandInit=sprintf('%s -e SUBJECTS_DIR=/data/freesurfer cgyan/dpabi bash -c ', CommandInit);
CommandParallel=sprintf('%s parallel -j %g', CommandInit, Cfg.ParallelWorkersNumber);

% smooth the surface files
% in the normalized space
SpaceName='fsaverage5';

for iGSR = 1:2
    Cfg.StartingDirName = GSRSet{iGSR};
    Cfg.StartingDirName_Volume = GSRVoluSet{iGSR};
     for iMask = 1:length(MaskVolumeSet)
        % prepare a .txt file listing all the subjects
        txtFile = [work_dir, '/filelist_', ...
            Cfg.StartingDirName,'_', MaskVolumeSet{iMask} ,'.txt'];
        DirImg=dir([work_dir,'/raw_FC_maps/FunSurfLH/FC_SeedSurfLHSurfRHVolu_', ...
            Cfg.StartingDirName,'_', MaskVolumeSet{iMask}, filesep,'*.gii']);
        fid = fopen(txtFile, 'w');
        for j = 1:length(DirImg)
            fprintf(fid, '%s\n', DirImg(j).name);
        end
        fclose(fid);
        txtFile_flag = ['/data/filelist_',Cfg.StartingDirName,'_', MaskVolumeSet{iMask} ,'.txt'];
        
        % left hemisphere
        if ~exist([work_dir,'/analyses/run_250929/raw_FC_mapsS/FunSurfLH/FC_SeedSurfLHSurfRHVolu_', ...
            Cfg.StartingDirName,'_', MaskVolumeSet{iMask}], 'dir')
         mkdir([work_dir,'/analyses/run_250929/raw_FC_mapsS/FunSurfLH/FC_SeedSurfLHSurfRHVolu_', ...
            Cfg.StartingDirName,'_', MaskVolumeSet{iMask}]);
        end
        Command = sprintf('%s "parallel -j %g mri_surf2surf --s %s --hemi lh --sval /data/%s/FunSurfLH/%s/{1}  --fwhm %g --cortex --tval /data/%sS/FunSurfLH/%s/s{1} :::: %s"', ...
                    CommandInit, Cfg.ParallelWorkersNumber, SpaceName, ...
                    'raw_FC_maps', ['FC_SeedSurfLHSurfRHVolu_', Cfg.StartingDirName,'_', MaskVolumeSet{iMask}], ...
                    Cfg.Smooth.FWHMSurf, ...
                    'raw_FC_maps', ['FC_SeedSurfLHSurfRHVolu_', Cfg.StartingDirName,'_', MaskVolumeSet{iMask}], ...
                    txtFile_flag);
        system(Command);

        % right hemisphere
         if ~exist([work_dir,'/analyses/run_250929/raw_FC_mapsS/FunSurfRH/FC_SeedSurfLHSurfRHVolu_', ...
            Cfg.StartingDirName,'_', MaskVolumeSet{iMask}], 'dir')
         mkdir([work_dir,'/analyses/run_250929/raw_FC_mapsS/FunSurfRH/FC_SeedSurfLHSurfRHVolu_', ...
            Cfg.StartingDirName,'_', MaskVolumeSet{iMask}]);
        end
        Command = sprintf('%s "parallel -j %g mri_surf2surf --s %s --hemi rh --sval /data/%s/FunSurfRH/%s/{1}  --fwhm %g --cortex --tval /data/%sS/FunSurfRH/%s/s{1} :::: %s"', ...
                    CommandInit, Cfg.ParallelWorkersNumber, SpaceName, ...
                    'raw_FC_maps', ['FC_SeedSurfLHSurfRHVolu_', Cfg.StartingDirName,'_', MaskVolumeSet{iMask}], ...
                    Cfg.Smooth.FWHMSurf, ...
                    'raw_FC_maps', ['FC_SeedSurfLHSurfRHVolu_', Cfg.StartingDirName,'_', MaskVolumeSet{iMask}], ...
                    txtFile_flag);
        system(Command);
     end
end

% smooth the volume files
if ~exist('n_par','var') || isempty(n_par), n_par = max(1, feature('numcores')-1); end
pool = gcp('nocreate');
if ~isempty(pool), delete(pool); end
parpool(n_par);

for iGSR = 1:2
    Cfg.StartingDirName = GSRSet{iGSR};
    Cfg.StartingDirName_Volume = GSRVoluSet{iGSR};
     for iMask = 1:length(MaskVolumeSet)

         FileList=[];
         for i=1:Cfg.SubjectNum 
                DirImg=dir([work_dir,'/raw_FC_maps/FunVolu/FC_SeedSurfLHSurfRHVolu_', ...
                    Cfg.StartingDirName_Volume,'_', MaskVolumeSet{iMask}, filesep,'*',Cfg.SubjectID{i},'*.nii']);
                for j=1:length(DirImg)
                    FileList=[FileList;{[work_dir,'/raw_FC_maps/FunVolu/FC_SeedSurfLHSurfRHVolu_', ...
                    Cfg.StartingDirName_Volume,'_', MaskVolumeSet{iMask}, filesep,DirImg(j).name]}];
                end
         end
         
         SPMJOB = load([ProgramPath,filesep,'Jobmats',filesep,'Smooth.mat']);
         parfor i = 1:numel(FileList)
            inFile = FileList{i};
            mb = SPMJOB.matlabbatch;
            mb{1}.spm.spatial.smooth.data   = {inFile};   
            mb{1}.spm.spatial.smooth.fwhm   =  Cfg.Smooth.FWHMVolu; 

            try
                spm_jobman('run', mb);
            catch ME
                warning('Smooth failed: %s\nfor: %s', inFile, ME.message);
            end
        end
         
        % copy smoothed files
         if ~exist([work_dir,'/raw_FC_mapsS/FunVolu/FC_SeedSurfLHSurfRHVolu_', ...
                Cfg.StartingDirName_Volume,'_', MaskVolumeSet{iMask}], 'dir')
            mkdir([work_dir,'/raw_FC_mapsS/FunVolu/FC_SeedSurfLHSurfRHVolu_', ...
                Cfg.StartingDirName_Volume,'_', MaskVolumeSet{iMask}]);
        end
        parfor i = 1:Cfg.SubjectNum 
            movefile([work_dir,'/raw_FC_maps/FunVolu/FC_SeedSurfLHSurfRHVolu_', ...
                Cfg.StartingDirName_Volume,'_', MaskVolumeSet{iMask},filesep,'s*',Cfg.SubjectID{i},'*'], ...
                [work_dir,'/raw_FC_mapsS/FunVolu/FC_SeedSurfLHSurfRHVolu_', ...
                Cfg.StartingDirName_Volume,'_', MaskVolumeSet{iMask}]);
        end
     end
end